const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('U', {
  storeGet: () => ipcRenderer.invoke('store-get'),
  storeSet: d => ipcRenderer.invoke('store-set', d),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  defaultFolders: () => ipcRenderer.invoke('default-folders'),
  scan: (folders, opts) => ipcRenderer.invoke('scan', folders, opts),
  onScanProgress: cb => ipcRenderer.on('scan-progress', (_, p) => cb(p)),
  search: q => ipcRenderer.invoke('search', q),
  searchLive: (q, rid) => ipcRenderer.send('search-live', q, rid),
  onSearchPart: cb => ipcRenderer.on('search-part', (_, p) => cb(p)),
  scStream: id => ipcRenderer.invoke('sc-stream', id),
  trending: (g, t) => ipcRenderer.invoke('trending', g, t),
  audiusSearch: q => ipcRenderer.invoke('audius-search', q),
  lyrics: (a, t, d, s) => ipcRenderer.invoke('lyrics', a, t, d, s),
  info: (t, a) => ipcRenderer.invoke('info', t, a),
  download: (u, n) => ipcRenderer.invoke('download', u, n),
  scDownload: id => ipcRenderer.invoke('sc-download', id),
  openPath: p => ipcRenderer.invoke('open-path', p),
  openUrl: u => ipcRenderer.invoke('open-url', u),
  titleColor: c => ipcRenderer.invoke('title-color', c),
  scRate: (r, k) => ipcRenderer.invoke('sc-rate', r, k),
  setAdblock: on => ipcRenderer.invoke('adblock', on),
  ytLogin: () => ipcRenderer.invoke('yt-login'),
  ytLogged: () => ipcRenderer.invoke('yt-logged'),
  ytLogout: () => ipcRenderer.invoke('yt-logout'),
  recommend: o => ipcRenderer.invoke('recommend', o),
  radio: t => ipcRenderer.invoke('radio', t),
  ytmCharts: gl => ipcRenderer.invoke('ytm-charts', gl),
  scCharts: r => ipcRenderer.invoke('sc-charts', r),
  ytmLists: gl => ipcRenderer.invoke('ytm-lists', gl),
  radios: o => ipcRenderer.invoke('radios', o),
  radioClick: id => ipcRenderer.invoke('radio-click', id),
  recStart: (st, o) => ipcRenderer.invoke('rec-start', st, o),
  onRecSong: cb => ipcRenderer.on('rec-song', (_, r) => cb(r)),
  icyNow: s => ipcRenderer.invoke('icy-now', s),
  huntConfig: c => ipcRenderer.invoke('hunt-config', c),
  huntScan: () => ipcRenderer.invoke('hunt-scan'),
  onHuntHit: cb => ipcRenderer.on('hunt-hit', (_, r) => cb(r)),
  onHuntNow: cb => ipcRenderer.on('hunt-now', (_, r) => cb(r)),
  netName: () => ipcRenderer.invoke('net-name'),
  focusWin: () => ipcRenderer.invoke('focus-win'),
  recStop: () => ipcRenderer.invoke('rec-stop'),
  onRecDone: cb => ipcRenderer.on('rec-done', (_, r) => cb(r)),
  ytmPlaylist: id => ipcRenderer.invoke('ytm-playlist', id),
  exportFx: (items, fx) => ipcRenderer.invoke('export-fx', items, fx),
  exportStop: () => ipcRenderer.invoke('export-stop'),
  onExportProgress: cb => ipcRenderer.on('export-progress', (_, p) => cb(p)),
  musicDir: () => ipcRenderer.invoke('music-dir'),
  frameEq: code => ipcRenderer.invoke('frame-eq', code),
  // libera memória (cache de imagens + coleta de lixo) quando o app vai pro fundo
  trim: () => { try { webFrame.clearCache(); } catch {} try { if (global.gc) global.gc(); } catch {} }
});
